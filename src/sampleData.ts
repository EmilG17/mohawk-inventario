export async function loadSampleCatalog(): Promise<number> {
  const products: Product[] = SAMPLE_PRODUCTS.map((p) => ({
    barcode: normalizeBarcode(p.barcode),
    sku: p.sku,
    description: p.description,
    unit: p.unit,
    expectedQty: p.expectedQty,
    minQty: p.minQty,
    maxQty: p.maxQty,
    unitCost: p.unitCost,
    brand: p.brand,
    source: 'catalogo',
    uncataloged: false,
  }));
  await bulkPutProducts(products, 'merge');
  return products.length;
}
